/** Типы утилит инспекции DOM для contenteditable-редактора. */

/** Результат поиска набранной пары inline-тега (`<b>текст</b>`) перед кареткой */
export interface TypedInlineTagMatch {
	/** Имя тега в нижнем регистре (из списка разрешённых) */
	tag: string
	/** Содержимое пары как обычный текст — HTML не разбирается */
	content: string
	/** Индекс начала открывающего тега в исходном тексте */
	start: number
}
