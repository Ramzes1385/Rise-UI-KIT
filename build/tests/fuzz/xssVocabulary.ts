function flipCase(rng: Rng, text: string): string {
	return [...text].map(char => (rng.chance(0.4) ? (rng.chance(0.5) ? char.toUpperCase() : char.toLowerCase()) : char)).join('')
}

const SEPARATORS = ['\t', '\n', '\r', '&Tab;', '&NewLine;', '&#9;', '&#x0A;', '&#13;', '\u0000', ' ', '\f', '&#0;', '\u000b']

function entityOf(rng: Rng, char: string): string {
	const code = char.charCodeAt(0)
	return rng.pick([
		`&#${code};`,
		`&#x${code.toString(16)};`,
		`&#x${code.toString(16).toUpperCase()}`,
		`&#${String(code).padStart(7, '0')};`,
		`&#X${code.toString(16)};`,
	] as const)
}

/** Схема с обфускацией: регистр, разделители между буквами, символы-сущности, управляющие символы в начале */
function obfuscateScheme(rng: Rng, scheme: string, mode: 'html' | 'plain'): string {
	const encode = mode === 'html'
	const letters = [...scheme].map(char => {
		let piece = rng.chance(0.4) ? (rng.chance(0.5) ? char.toUpperCase() : char) : char
		if (encode && rng.chance(0.15)) piece = entityOf(rng, piece)
		if (rng.chance(0.08)) piece += encode ? rng.pick(SEPARATORS) : rng.pick(['\t', '\n', '\r'] as const)
		return piece
	})
	const colon = encode && rng.chance(0.2) ? rng.pick([':', '&colon;', '&#58;', '&#x3a;', '&#x3A'] as const) : ':'
	const lead = rng.chance(0.2)
		? rng.pick(['', ' ', '\n', '\t', '\u0001', '\u0000', '\u001f', '  ', '&#1;', '&#x20;', '\u00a0', '\ufeff', '\u200b'] as const)
		: ''
	return `${lead}${letters.join('')}${colon}`
}

export function dangerousUrl(rng: Rng, mode: 'html' | 'plain'): string {
	if (rng.chance(0.25)) return rng.pick(SAFE_URLS)
	const scheme = rng.pick(SCHEMES)
	const head = obfuscateScheme(rng, scheme, mode)
	if (scheme === 'data') return `${head}${rng.pick(DATA_PAYLOADS)}`
	return `${head}${rng.chance(0.7) ? rng.pick(SCRIPT_PAYLOADS) : '//example.com/'}`
}

